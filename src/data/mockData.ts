// Generate 30 days of daily metrics
export const generateDailyMetrics = (): Metric[] => {
  const metrics: Metric[] = [];
  const platforms = ['instagram', 'tiktok', 'spotify', 'youtube', 'apple_music'];
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    const trendFactor = 1 + (30 - i) * 0.015; // upward organic curve

    platforms.forEach((p) => {
      let baseFollowers = 300000;
      let baseReach = 40000;
      let baseViews = 80000;
      let baseStreams = 25000;

      if (p === 'instagram') {
        baseFollowers = 310000 + (30 - i) * 1250;
        baseReach = Math.round((45000 + Math.sin(i * 0.7) * 9000) * trendFactor);
        baseViews = Math.round((110000 + Math.sin(i * 0.5) * 24000) * trendFactor);
        baseStreams = 0;
      } else if (p === 'tiktok') {
        baseFollowers = 240000 + (30 - i) * 1800;
        baseReach = Math.round((70000 + Math.cos(i * 0.9) * 18000) * trendFactor);
        baseViews = Math.round((140000 + Math.cos(i * 0.8) * 35000) * trendFactor);
        baseStreams = 0;
      } else if (p === 'spotify') {
        baseFollowers = 150000 + (30 - i) * 1100;
        baseReach = Math.round((32000 + Math.sin(i * 0.4) * 5000) * trendFactor);
        baseViews = Math.round((48000 + Math.sin(i * 0.6) * 8000) * trendFactor);
        baseStreams = Math.round((38000 + Math.sin(i * 0.5) * 7500) * trendFactor);
      } else if (p === 'youtube') {
        baseFollowers = 88000 + (30 - i) * 350;
        baseReach = Math.round((18000 + Math.sin(i * 0.8) * 3200) * trendFactor);
        baseViews = Math.round((28000 + Math.cos(i * 0.5) * 6000) * trendFactor);
        baseStreams = 0;
      } else {
        baseFollowers = 40000 + (30 - i) * 200;
        baseReach = Math.round((11000 + Math.sin(i * 0.3) * 2000) * trendFactor);
        baseViews = Math.round((14000 + Math.sin(i * 0.4) * 2500) * trendFactor);
        baseStreams = Math.round((8500 + Math.cos(i * 0.5) * 1500) * trendFactor);
      }

      metrics.push({
        id: `met_${p}_${dateStr}`,
        socialAccountId: `acc_${p}`,
        platform: p,
        date: dateStr,
        followers: baseFollowers,
        reach: baseReach,
        impressions: Math.round(baseReach * 1.4),
        views: baseViews,
        engagement: Number((4.5 + Math.sin(i) * 1.2).toFixed(1)),
        clicks: Math.round(baseViews * 0.038),
        saves: Math.round(baseViews * 0.062),
        shares: Math.round(baseViews * 0.024),
        streams: baseStreams,
        watchTimeHours: Math.round(baseViews * 0.012),
      });
    });
  }

  return metrics;
};

